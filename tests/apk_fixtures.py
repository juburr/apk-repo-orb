#!/usr/bin/env python3
"""Builds APK packages and indexes for the offline tests, as melange does.

A stand-in for melange's keygen, sign and index, standard library only,
signing with the openssl CLI. The golden tests in CI (T-3) check the orb
against real melange too; this file only has to be close enough for the
offline tests to mean something.

  apk_fixtures.py keygen PRIVATE                      (PRIVATE.pub too)
  apk_fixtures.py build OUT NAME VERSION ARCH [--key PRIVATE] [--file PATH=TEXT]...
  apk_fixtures.py sign PRIVATE APK...                 (in place)
  apk_fixtures.py index OUT [--source SRC --merge] [--key PRIVATE] [--legacy] APK...

As the tests' melange stand-in (tests/stubs/melange), it also takes
melange's own flags: sign --signing-key K, index -o OUT -s SRC -m --signing-key K.
"""

import base64
import gzip
import hashlib
import io
import os
import subprocess
import sys
import tarfile
import time


def gz(data):
    return gzip.compress(data, mtime=0)


def tar_entry(name, data, mtime=0):
    info = tarfile.TarInfo(name)
    info.size = len(data)
    info.mtime = mtime
    info.mode = 0o644
    header = info.tobuf(tarfile.USTAR_FORMAT, "utf-8", "surrogateescape")
    return header + data + b"\0" * ((512 - len(data) % 512) % 512)


def cut_tar(entries):
    """A tar stream without end-of-archive blocks, as APK segments are."""
    return b"".join(tar_entry(name, data) for name, data in entries)


def full_tar(entries):
    return cut_tar(entries) + b"\0" * 1024


def openssl_sign(key, data, digest="-sha256"):
    result = subprocess.run(["openssl", "dgst", digest, "-sign", key], input=data,
                            stdout=subprocess.PIPE, check=True)
    return result.stdout


def signature_member(key, data, legacy=False):
    name = os.path.basename(key)
    if legacy:
        entry = ".SIGN.RSA.%s.pub" % name
        signature = openssl_sign(key, data, "-sha1")
    else:
        entry = ".SIGN.RSA256.%s.pub" % name
        signature = openssl_sign(key, data)
    return gz(cut_tar([(entry, signature)]))


def members(data):
    """Splits concatenated gzip members: [(compressed, decompressed)]."""
    out = []
    rest = data
    while rest:
        import zlib
        inflate = zlib.decompressobj(31)
        plain = inflate.decompress(rest)
        used = len(rest) - len(inflate.unused_data)
        out.append((rest[:used], plain))
        rest = inflate.unused_data
    return out


def tar_names(plain):
    return [m.name for m in tarfile.open(fileobj=io.BytesIO(plain), mode="r:")]


def split_apk(data):
    """Returns (signature member or None, control member, data members)."""
    parts = members(data)
    if ".PKGINFO" in tar_names(parts[0][1]):
        return None, parts[0], parts[1:]
    return parts[0], parts[1], parts[2:]


def build(out, name, version, arch, key=None, files=None):
    files = files or {"usr/share/%s/README" % name: "%s %s\n" % (name, version)}
    data_tar = full_tar([(path, text.encode("utf-8")) for path, text in sorted(files.items())])
    data = gz(data_tar)
    installed = sum(len(text.encode("utf-8")) for text in files.values())
    pkginfo = ("# Generated by the apk-repo-orb tests\n"
               "pkgname = %s\npkgver = %s\narch = %s\nsize = %d\norigin = %s\n"
               "pkgdesc = %s for the tests\nlicense = MIT\ndatahash = %s\n"
               % (name, version, arch, installed, name, name, hashlib.sha256(data).hexdigest()))
    control = gz(cut_tar([(".PKGINFO", pkginfo.encode("utf-8"))]))
    with open(out, "wb") as stream:
        if key:
            stream.write(signature_member(key, control))
        stream.write(control)
        stream.write(data)


def sign(key, path):
    with open(path, "rb") as stream:
        data = stream.read()
    _, control, rest = split_apk(data)
    with open(path, "wb") as stream:
        stream.write(signature_member(key, control[0]))
        stream.write(control[0])
        for member in rest:
            stream.write(member[0])


def pkginfo(control_plain):
    tar = tarfile.open(fileobj=io.BytesIO(control_plain), mode="r:")
    text = tar.extractfile(tar.getmember(".PKGINFO")).read().decode("utf-8")
    info = {}
    for line in text.splitlines():
        if " = " in line and not line.startswith("#"):
            key, value = line.split(" = ", 1)
            info.setdefault(key, value)
    return info


def entry(path):
    with open(path, "rb") as stream:
        data = stream.read()
    _, control, _ = split_apk(data)
    info = pkginfo(control[1])
    checksum = "Q1" + base64.b64encode(hashlib.sha1(control[0]).digest()).decode("ascii")
    return [("C", checksum), ("P", info["pkgname"]), ("V", info["pkgver"]), ("A", info["arch"]),
            ("S", str(len(data))), ("I", info.get("size", "0")), ("T", info.get("pkgdesc", "")),
            ("U", ""), ("L", info.get("license", "")), ("o", info.get("origin", "")),
            ("t", str(int(time.time())))]


def read_index(path):
    with open(path, "rb") as stream:
        data = stream.read()
    parts = members(data)
    plain = b"".join(part[1] for part in parts[1:])
    tar = tarfile.open(fileobj=io.BytesIO(plain), mode="r:")
    text = tar.extractfile(tar.getmember("APKINDEX")).read().decode("utf-8")
    records = []
    for block in text.split("\n\n"):
        lines = [line for line in block.split("\n") if line]
        if lines:
            records.append([(line[0], line[2:]) for line in lines])
    return records


def index(out, apks, key=None, source=None, merge=False, legacy=False):
    records = read_index(source) if merge and source and os.path.exists(source) else []
    for path in apks:
        new = entry(path)
        name, version = dict(new)["P"], dict(new)["V"]
        for number, record in enumerate(records):
            if dict(record)["P"] == name and dict(record)["V"] == version:
                records[number] = new
                break
        else:
            records.append(new)
    text = "".join("".join("%s:%s\n" % field for field in record) + "\n" for record in records)
    signed = gz(full_tar([("APKINDEX", text.encode("utf-8")), ("DESCRIPTION", b"")]))
    with open(out, "wb") as stream:
        if key:
            stream.write(signature_member(key, signed, legacy))
        stream.write(signed)


def keygen(private):
    # PKCS#1 (BEGIN RSA PRIVATE KEY), as melange keygen writes it.
    subprocess.run(["openssl", "genrsa", "-traditional", "-out", private, "2048"], check=True, stderr=subprocess.DEVNULL)
    subprocess.run(["openssl", "rsa", "-in", private, "-pubout", "-out", private + ".pub"],
                   check=True, stderr=subprocess.DEVNULL)


def main(argv):
    command, args = argv[1], argv[2:]
    if command == "keygen":
        keygen(args[0])
    elif command == "build":
        out, name, version, arch = args[:4]
        key, files = None, {}
        rest = args[4:]
        while rest:
            if rest[0] == "--key":
                key, rest = rest[1], rest[2:]
            elif rest[0] == "--file":
                path, text = rest[1].split("=", 1)
                files[path] = text
                rest = rest[2:]
            else:
                raise SystemExit("unknown option %s" % rest[0])
        build(out, name, version, arch, key, files or None)
    elif command == "sign":
        key, paths = None, []
        while args:
            if args[0] in ("--signing-key", "-k"):
                key, args = args[1], args[2:]
            elif key is None:
                key, args = args[0], args[1:]
            else:
                paths.append(args[0])
                args = args[1:]
        for path in paths:
            sign(key, path)
    elif command == "index":
        out, key, source, merge, legacy, apks = None, None, None, False, False, []
        if args and not args[0].startswith("-"):
            out, args = args[0], args[1:]
        while args:
            flag = args[0]
            if flag in ("-o", "--output"):
                out, args = args[1], args[2:]
            elif flag in ("-s", "--source"):
                source, args = args[1], args[2:]
            elif flag in ("--key", "--signing-key"):
                key, args = args[1], args[2:]
            elif flag in ("-m", "--merge"):
                merge, args = True, args[1:]
            elif flag == "--legacy":
                legacy, args = True, args[1:]
            elif flag in ("-a", "--arch"):
                args = args[2:]
            else:
                apks.append(flag)
                args = args[1:]
        index(out or "APKINDEX.tar.gz", apks, key, source, merge, legacy)
    else:
        raise SystemExit("unknown command %s" % command)


if __name__ == "__main__":
    main(sys.argv)
